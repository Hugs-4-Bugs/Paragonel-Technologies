// scripts/gen-env-local.js — regenerate the gitignored .env.local for LOCAL DEV ONLY.
//
// Why this exists: .env.local is gitignored (never committed) and is wiped when
// the Z.ai workspace is recycled. Re-running this script restores a working dev
// environment without any committed secrets.
//
// Portable: resolves the repo root from this file's location (__dirname/..), so
// it works from any clone. Run from the repo root:
//   node scripts/gen-env-local.js
//
// What it sets (LOCAL DEV ONLY):
//   - JWT_SECRET            strong random (>= 32 chars) — admin JWT signing
//   - ADMIN_EMAIL           admin@example.com (dev login, per docs/RUNTIME.md)
//   - ADMIN_PASSWORD_HASH   bcrypt hash of the dev password "TestAdmin123!"
//                           with literal `$` escaped as `\$` so dotenv-expand
//                           does not mangle $2a / $10 / $<rest> into empty vars
//   - FIRESTORE_EMULATOR_HOST=localhost:8080  -> Admin SDK uses the emulator
//                           (no real Firebase service-account credentials)
//   - NEXT_PUBLIC_FIREBASE_*  dev placeholder values (NON-EMPTY only, so that
//                           src/firebase/config.ts does not throw at module
//                           load). The client SDK is NOT wired to the emulator,
//                           so client-side Firestore reads will not return data
//                           in local dev; server-side (Admin SDK) reads do.
//   - SMTP_*                left EMPTY here — real SMTP credentials are the
//                           founder's to provide for the SMTP-OTP auth phase
//                           (see docs/AUTH_IMPLEMENTATION_PLAN.md).

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const repoRoot = path.resolve(__dirname, '..');
const envPath = path.join(repoRoot, '.env.local');

let bcrypt;
try {
  // Bare require resolves from the repo's node_modules (this script lives in
  // <repo>/scripts, so Node walks up to <repo>/node_modules).
  bcrypt = require('bcryptjs');
} catch (e) {
  console.error('bcryptjs not found in repo node_modules. Run `npm install` first.');
  process.exit(1);
}

const jwtSecret = crypto.randomBytes(48).toString('base64url'); // ~64 chars
const rawHash = bcrypt.hashSync('TestAdmin123!', 10);            // e.g. $2a$10$...
const escapedHash = rawHash.replace(/\$/g, '\\$');               // $ -> \$  (dotenv-expand safe)

const lines = [
  '# .env.local — LOCAL DEV ONLY. Regenerated by scripts/gen-env-local.js.',
  '# NEVER commit this file (.env* is gitignored). No real production secrets here.',
  '',
  '# --- Admin auth (local dev) ---',
  `JWT_SECRET=${jwtSecret}`,
  'ADMIN_EMAIL=admin@example.com',
  `ADMIN_PASSWORD_HASH=${escapedHash}`,
  '',
  '# --- Firestore emulator (Admin SDK local mode — no real credentials) ---',
  'FIRESTORE_EMULATOR_HOST=localhost:8080',
  'FIREBASE_ADMIN_PROJECT_ID=paragonel-dev',
  '',
  '# --- Firebase client config (dev placeholders; NON-EMPTY so src/firebase/config.ts',
  '#     does not throw at module load. Client SDK is not emulator-wired, so client-side',
  '#     Firestore reads return nothing locally; server-side Admin SDK reads do.) ---',
  'NEXT_PUBLIC_FIREBASE_API_KEY=AIzaSyDevPlaceholderKeyForEmulatorOnly000',
  'NEXT_PUBLIC_FIREBASE_AUTH_DOMAIN=paragonel-dev.firebaseapp.com',
  'NEXT_PUBLIC_FIREBASE_PROJECT_ID=paragonel-dev',
  'NEXT_PUBLIC_FIREBASE_STORAGE_BUCKET=paragonel-dev.appspot.com',
  'NEXT_PUBLIC_FIREBASE_MESSAGING_SENDER_ID=000000000000',
  'NEXT_PUBLIC_FIREBASE_APP_ID=1:000000000000:web:0000000000000000000000',
  'NEXT_PUBLIC_FIREBASE_MEASUREMENT_ID=',
  '',
  '# --- Auth redesign env (documented in .env.example; NOT enforced yet) ---',
  'SUPERADMIN_BOOTSTRAP_EMAIL=contact@prabhat.online',
  `OTP_SECRET=${crypto.randomBytes(48).toString('base64url')}`,
  '',
  '# --- SMTP (LEFT EMPTY — founder provides real SMTP creds for the OTP auth phase) ---',
  'SMTP_HOST=',
  'SMTP_PORT=',
  'SMTP_SECURE=',
  'SMTP_USER=',
  'SMTP_PASS=',
  'SMTP_FROM=',
  '',
  '# --- App ---',
  'APP_BASE_URL=http://localhost:3000',
  'COMPANY_INBOX=contact@paragonel.com',
  'GEMINI_API_KEY=',
  'GOOGLE_API_KEY=',
  '',
];

fs.writeFileSync(envPath, lines.join('\n') + '\n', { mode: 0o600 });

// Verify the hash round-trips (sanity check the escaping did not corrupt it).
const ok = bcrypt.compareSync('TestAdmin123!', rawHash);
console.log(`Wrote ${envPath} (${lines.length} lines)`);
console.log(`JWT_SECRET length: ${jwtSecret.length} chars`);
console.log(`ADMIN_PASSWORD_HASH: bcrypt hash, verify(TestAdmin123!) = ${ok}`);
console.log(`$ escaping: ${rawHash.replace(/[^$]/g, '').length} '$' chars -> escaped`);
